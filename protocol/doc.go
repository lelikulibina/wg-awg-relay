// Package protocol предоставляет независимые от операционной системы типы
// конфигурации WireGuard/AmneziaWG, алгоритмы маршрутизации и кодек UAPI.
//
// Пакет не открывает сокеты и не управляет сетевыми интерфейсами. Он отвечает
// за проверку конфигурации, нормализацию префиксов, выбор пира по адресу
// назначения и формирование запросов к UAPI AmneziaWG/WireGuard.
//
// Адреса и MTU TUN-интерфейса намеренно не включены в UAPI: ими управляет
// отдельный платформенный сетевой адаптер. Реальный движок релея будет уровнем
// выше и сможет применять UAPI-запросы без пересоздания туннеля.
//
// Для выбора маршрута применяется longest-prefix match. Приоритет сравнивается
// только у маршрутов с одинаковой длиной префикса. При равенстве приоритетов
// выбирается лексикографически меньший идентификатор пира.
