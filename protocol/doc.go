// Package protocol предоставляет независимые от операционной системы типы
// конфигурации WireGuard/AmneziaWG, алгоритмы маршрутизации и кодек UAPI.
//
// Пакет не создаёт TUN-интерфейсы и не открывает UDP-транспорт WireGuard.
// UAPIClient подключается только к локальному IPC Unix-сокету уже работающего
// устройства для применения конфигурации и чтения его состояния.
//
// Пакет отвечает за проверку конфигурации, нормализацию префиксов, выбор пира
// по адресу назначения и формирование запросов к UAPI AmneziaWG/WireGuard.
// Адреса и MTU TUN-интерфейса остаются ответственностью платформенного
// сетевого адаптера.
//
// Для выбора маршрута применяется longest-prefix match. Приоритет сравнивается
// только у маршрутов с одинаковой длиной префикса. При равенстве приоритетов
// выбирается лексикографически меньший идентификатор пира.
